/// Box-average a glyph bbox (squared, centered) to GLYPH_SIZE x GLYPH_SIZE
/// ink-density values in [0, 1], row-major. Padding is white (density 0).
fn crop_glyph_box(
    mask: &[bool],
    size: usize,
    x0: usize,
    x1: usize,
    y0: usize,
    y1: usize,
) -> [f32; GLYPH_DIM] {
    let w = x1 - x0;
    let h = y1 - y0;
    let s = w.max(h).max(1);
    let ox = (s - w) / 2;
    let oy = (s - h) / 2;
    let mut sq = alloc::vec![false; s * s];
    for gy in 0..h {
        for gx in 0..w {
            sq[(oy + gy) * s + (ox + gx)] = mask[(y0 + gy) * size + (x0 + gx)];
        }
    }
    let mut crop = [0.0f32; GLYPH_DIM];
    for dy in 0..GLYPH_SIZE {
        let sy0 = dy * s / GLYPH_SIZE;
        let sy1 = ((dy + 1) * s / GLYPH_SIZE).max(sy0 + 1);
        for dx in 0..GLYPH_SIZE {
            let sx0 = dx * s / GLYPH_SIZE;
            let sx1 = ((dx + 1) * s / GLYPH_SIZE).max(sx0 + 1);
            let mut ink = 0usize;
            let n = (sy1 - sy0) * (sx1 - sx0);
            for sy in sy0..sy1 {
                for sx in sx0..sx1 {
                    if sq[sy * s + sx] {
                        ink += 1;
                    }
                }
            }
            crop[dy * GLYPH_SIZE + dx] = ink as f32 / n as f32;
        }
    }
    crop
}

/// Extract all glyph crops from a deskewed ink mask + line bands.
/// Returns `count * GLYPH_DIM` f32 values, one 20x20 crop after another.
pub fn glyph_crops_from_mask(mask: &[bool], size: usize, bands: &[(usize, usize)]) -> Vec<f32> {
    let mut out = Vec::new();
    for_each_glyph_bbox(mask, size, bands, |x0, x1, y0, y1| {
        let crop = crop_glyph_box(mask, size, x0, x1, y0, y1);
        out.extend_from_slice(&crop);
    });
    out
}

/// Page-level evidence over glyph crops: the sum of per-glyph logistic
/// log-odds (linear scores). Positive = flipped; negative = upright.
/// Returns `(sum_logodds, glyph_count)`.
pub fn glyph_logodds_from_crops(crops: &[f32]) -> (f64, usize) {
    let count = crops.len() / GLYPH_DIM;
    let mut sum = 0.0f64;
    for c in crops.chunks_exact(GLYPH_DIM) {
        let mut z = GLYPH_INTERCEPT as f64;
        for i in 0..GLYPH_DIM {
            z += GLYPH_COEFS[i] as f64 * c[i] as f64;
        }
        sum += z;
    }
    (sum, count)
}

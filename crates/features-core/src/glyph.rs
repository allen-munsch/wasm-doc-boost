//! Per-glyph 0-vs-180 flip classifier.
//!
//! Invoices are heavy on all-caps and lining digits: ascender/descender ink
//! mass is ~0, so flip_score and vote_frac (asc/desc ink) are coin flips
//! there. The glyph SHAPES still disambiguate the flip: a small logistic
//! classifier on 20x20 glyph crops only has to be modestly above chance per
//! glyph, and summing the per-glyph log-odds over the page makes the
//! page-level error shrink as the glyph count grows.
//!
//! Crops come from the SAME deskewed ink mask + line bands as the flip
//! features (one deskew, one binarization). Each glyph bbox is squared
//! (centered) and box-averaged to 20x20 so thin strokes survive downsampling
//! (nearest-neighbour would alias them away at 512px long-edge export).
//!
//! Weights are baked from `scripts/train_glyph_classifier.py` (fatura2,
//! image-level split): L2 logistic regression on the crops (C=1.0), then a
//! page-level calibration logistic on (sum_logodds, glyph_count).

